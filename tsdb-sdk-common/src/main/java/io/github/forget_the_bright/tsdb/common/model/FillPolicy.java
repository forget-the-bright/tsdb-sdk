package io.github.forget_the_bright.tsdb.common.model;

/**
 * 插值查询（{@link QueryMode#INTERPOLATED}）在时间片无原始采样点时的补齐策略。
 *
 * <p>插值查询会按 {@link HistoryQuery#getInterval()} 把查询区间切成等宽时间片，
 * 并在每个时间片的时间戳处产出一个结果点。若该时刻附近没有可用于插值的原始点
 * （例如数据中断、区间两端之外），则由本枚举决定该点如何补齐。</p>
 *
 * <p>约定：补齐出来的点其 {@link Sample#getQuality()} 应为
 * {@link Quality#UNCERTAIN}（{@link #ZERO} 与 {@link #NULL} 亦同），
 * 以免下游把补点误当作实测值；具体质量码由驱动决定但需在驱动文档中说明。</p>
 *
 * <p>本枚举不可变、线程安全。</p>
 *
 * @author wanghao
 * @since 0.1.0
 */
public enum FillPolicy {
    /**
     * 不补齐：无数据的时间片直接跳过，不产出结果点。
     * 结果序列可能因此出现时间上的空洞，长度也可能小于预期的时间片数量。
     * 这是默认策略。
     */
    NONE,

    /**
     * 前值保持：用该时间片之前（不含本片）最近一个有效采样点的值填充。
     * 若查询区间起点之前也没有任何历史点，则该片仍无法填充，按 {@link #NONE}
     * 处理。适合开关量、状态量这类阶梯型信号。
     */
    PREVIOUS,

    /**
     * 线性插值：取该时间片前后最近的两个有效采样点，按时间距离做线性插值。
     * 若前或后任一方向缺失（落在数据边界之外），该片无法插值，按 {@link #NONE}
     * 处理。适合连续变化的模拟量。
     */
    LINEAR,

    /**
     * 零值填充：无数据的时间片一律填 0。注意 0 在此处是“缺数据”的占位，
     * 并不代表真实测量值为 0，下游统计时需结合质量码区分。
     */
    ZERO,

    /**
     * 空值填充：无数据的时间片产出一个值为 {@code null} 的采样点
     * （{@link Sample#isNull()} 为 {@code true}），从而保证结果点数量与
     * 时间片数量严格一致。适合需要与时间轴严格对齐的绘图场景。
     */
    NULL
}
